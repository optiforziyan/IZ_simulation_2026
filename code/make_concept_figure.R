args<-commandArgs(); script<-sub('^--file=','',args[grepl('^--file=',args)][1])
root<-normalizePath(file.path(dirname(script),'..'),winslash='/')
draw<-function() {
 par(mar=c(0,0,0,0)); plot.new(); plot.window(xlim=c(0,15),ylim=c(0,9),xaxs='i',yaxs='i')
 rect(0,0,15,9,col='white',border=NA)
 text(7.5,8.5,'Equal local scores can conceal different biological identities',cex=1.3,font=2,col='#19324b')
 xx<-c(.35,5.4,10.45); cols<-c('#eaf2f8','#fff4da','#eaf4e5')
 heads<-c('1  Equal local summaries','2  Valid index targets','3  Explicit entity targets')
 for(k in 1:3) {rect(xx[k],1.5,xx[k]+4.2,7.9,col=cols[k],border='#bdc9d1');text(xx[k]+2.1,7.45,heads[k],font=2,cex=1.05,col='#19324b')}
 text(2.45,6.85,'Planning unit       A       B       C',font=2,cex=.95)
 labels<-c('SR                     8       8       8','PD                   20     20     20','FD                     4       4       4','GD                  0.8    0.8    0.8')
 for(i in 1:4) text(2.45,6.35-(i-1)*.48,labels[i],cex=.95)
 text(2.45,3.9,'A and B share the same entities.',cex=.91)
 text(2.45,3.25,'C contains different species,\nadditional branches, functional entities\nand genetic lineages.',cex=.91)
 text(2.45,2.15,'Equal scalar values do not encode identity.',cex=.86,font=2)
 text(7.5,6.5,'Indices can be conservation features\nwhen spatially defined and assigned\nexplicit representation targets.',cex=1)
 text(7.5,4.8,'However, equal index values alone\ndo not distinguish B from C\nafter A has been selected.',cex=1)
 text(7.5,2.8,'Meeting index targets does not guarantee\nrepresentation of underlying entities.',cex=.95,font=2)
 text(12.55,6.5,'Given A is already selected:',font=2,cex=1)
 text(12.55,5.5,'B adds repeated entities.\nC adds previously unrepresented entities.',cex=.96)
 text(12.55,4.1,'Hard targets protect the entities\nthat are explicitly included.',cex=1,font=2)
 text(12.55,2.75,'Local indices can guide spatial preference;\nthey do not create representation\nguarantees for omitted entities.',cex=.96)
 arrows(4.65,4.6,5.3,4.6,length=.12,col='#738292',lwd=2)
 arrows(9.7,4.6,10.35,4.6,length=.12,col='#738292',lwd=2)
 text(7.5,.94,'All values are hypothetical illustrations, not empirical estimates.',cex=.96,font=2)
 text(7.5,.48,'SR: species richness   |   PD: phylogenetic diversity   |   FD: functional diversity   |   GD: genetic diversity',cex=.87)
}
png(file.path(root,'figures/00_conceptual_framework.png'),width=3600,height=2160,res=240);draw();dev.off()
svg(file.path(root,'figures/00_conceptual_framework.svg'),width=15,height=9);draw();dev.off()
